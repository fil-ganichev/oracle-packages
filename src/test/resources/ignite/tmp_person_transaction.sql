DROP TABLE IF EXISTS TMP_PERSON;

CREATE TABLE TMP_PERSON (
  pid DECIMAL PRIMARY KEY,
  name VARCHAR,
  dep_id DECIMAL,
  age DECIMAL
) WITH "ATOMICITY=TRANSACTIONAL,TEMPLATE=REPLICATED,CACHE_NAME=TBG_TMP_PERSON,KEY_TYPE=TBG_TMP_PERSON_KEY,VALUE_TYPE=TBG_TMP_PERSON_ROW";

-- KEY_TYPE / VALUE_TYPE для non-SQL API; WRAP_KEY по умолчанию false (одиночный PK = Decimal в кэше).
